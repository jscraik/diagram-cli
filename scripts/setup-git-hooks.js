#!/usr/bin/env node
/**
 * Setup script for prek-managed git hooks.
 *
 * Run this script from the repository root to install the canonical
 * pre-commit, pre-push, and commit-msg hooks declared in prek.toml.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const PREK_CONFIG_PATH = resolve(process.cwd(), "prek.toml");
const COMMIT_MSG_VALIDATOR_PATH = resolve(process.cwd(), "scripts/validate-commit-msg.js");
const REPO_LOCAL_PREK_HOME = resolve(process.cwd(), ".git/.cache/prek");
const INSTALLED_HOOKS = [
	"pre-commit: make hooks-pre-commit",
	"pre-push: make hooks-pre-push",
	"commit-msg: node scripts/validate-commit-msg.js",
];
const WRAPPER_TARGETS = ['make hooks-commit-msg HOOK_COMMIT_MSG="feat: example"'];
const PREK_HOOK_MARKER = "# File generated by prek: https://github.com/j178/prek";
const PREK_HOOK_PATCH = [
	"# Keep prek cache/logs in repo-local .git to avoid home-dir sandbox write failures",
	'PREK_HOME="${PREK_HOME:-$HERE/../.cache/prek}"',
	'mkdir -p "$PREK_HOME" 2>/dev/null || true',
	"export PREK_HOME",
	"",
].join("\n");

function clearLegacyLocalHooksPath() {
	try {
		const configuredHooksPath = execFileSync(
			"git",
			["config", "--local", "--get", "core.hooksPath"],
			{
				encoding: "utf8",
				stdio: ["ignore", "pipe", "ignore"],
			},
		).trim();
		if (!configuredHooksPath) {
			return;
		}

		console.info(
			`Removing legacy local core.hooksPath ('${configuredHooksPath}') so prek can install canonical hooks...`,
		);
		execFileSync("git", ["config", "--unset-all", "--local", "core.hooksPath"], {
			stdio: "inherit",
		});
	} catch {
		// No local core.hooksPath override is present.
	}
}

function patchInstalledPrekHooks() {
	const hooksDir = resolve(process.cwd(), ".git/hooks");
	if (!existsSync(hooksDir)) {
		return 0;
	}

	let patchedCount = 0;
	for (const hookName of readdirSync(hooksDir)) {
		const hookPath = resolve(hooksDir, hookName);
		let hookContent = "";
		try {
			hookContent = readFileSync(hookPath, "utf8");
		} catch {
			continue;
		}

		if (!hookContent.includes(PREK_HOOK_MARKER)) {
			continue;
		}
		if (hookContent.includes('PREK_HOME="${PREK_HOME:-$HERE/../.cache/prek}"')) {
			continue;
		}

		const patched = hookContent.replace(
			'fi\n\nexec "$PREK" hook-impl',
			`fi\n\n${PREK_HOOK_PATCH}exec "$PREK" hook-impl`,
		);
		if (patched === hookContent) {
			continue;
		}

		writeFileSync(hookPath, patched);
		patchedCount += 1;
	}

	return patchedCount;
}

function main() {
	if (!existsSync(PREK_CONFIG_PATH)) {
		console.error("Error: prek.toml not found in current directory");
		console.error("  Run this script from the repository root.");
		process.exit(1);
	}

	if (!existsSync(COMMIT_MSG_VALIDATOR_PATH)) {
		console.error(
			"Error: scripts/validate-commit-msg.js is required for commit message validation.",
		);
		process.exit(1);
	}

	console.info("Installing prek hooks from prek.toml...");
	try {
		clearLegacyLocalHooksPath();
		mkdirSync(REPO_LOCAL_PREK_HOME, { recursive: true });
		execFileSync("prek", ["install"], {
			env: {
				...process.env,
				PREK_HOME: process.env.PREK_HOME || REPO_LOCAL_PREK_HOME,
			},
			stdio: "inherit",
		});
		const patchedCount = patchInstalledPrekHooks();
		if (patchedCount > 0) {
			console.info(`Patched ${patchedCount} prek hook shim(s) with repo-local PREK_HOME`);
		}
	} catch (error) {
		const message =
			error instanceof Error && error.message
				? error.message
				: "unknown prek installation failure";
		console.error("\nFailed to run 'prek install'.");
		console.error("Ensure `prek` is installed and available on PATH, then retry.");
		console.error(`Underlying error: ${message}`);
		process.exit(1);
	}

	console.info("\n✓ Git hooks installed and active via prek");
	console.info("\nInstalled git hooks:");
	for (const hookDescription of INSTALLED_HOOKS) {
		console.info(`  • ${hookDescription}`);
	}
	console.info("\nAvailable governance wrapper targets:");
	for (const wrapperTarget of WRAPPER_TARGETS) {
		console.info(`  • ${wrapperTarget}`);
	}
}

main();
